def _task_id(request: Any) -> str:
    if not isinstance(request, Mapping):
        raise ValueError("request must be an object")
    task_id = request.get("task_id")
    parameters = request.get("task_parameters")
    if not isinstance(task_id, str) or not task_id:
        raise ValueError("request.task_id must be a non-empty string")
    if not isinstance(parameters, Mapping):
        raise ValueError("request.task_parameters must be an object")
    return task_id


class ReferenceKukaIiwa14Driver:
    """Replay reviewed joint targets through canonical position actuators."""

    def __init__(self, *, model: Any, data: Any) -> None:
        self.model = model
        self.data = data
        self._actuator_ids = tuple(self._actuator_id(name) for name in ACTUATORS)

    def _actuator_id(self, name: str) -> int:
        actuator_id = int(mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_ACTUATOR, name))
        if actuator_id < 0:
            raise ValueError(f"canonical model is missing actuator {name!r}")
        return actuator_id

    def _set_target(self, target: np.ndarray) -> None:
        for actuator_id, value in zip(self._actuator_ids, target, strict=True):
            self.data.ctrl[actuator_id] = float(value)

    def _run_task(self, request: Any, allowed_task_ids: frozenset[str]) -> None:
        task_id = _task_id(request)
        if task_id not in allowed_task_ids:
            raise ValueError(f"task {task_id!r} is not assigned to this capability")
        plan = JOINT_PLANS.get(task_id)
        if plan is None:
            raise ValueError(f"no reviewed calibration trajectory for task {task_id!r}")
        for segment in plan:
            target = np.asarray(segment["q"], dtype=float)
            steps = int(segment["steps"])
            if target.shape != (len(self._actuator_ids),) or not np.isfinite(target).all():
                raise ValueError("joint target must contain seven finite values")
            if steps <= 0:
                raise ValueError("trajectory segment steps must be positive")
            start = np.asarray(
                [self.data.ctrl[actuator_id] for actuator_id in self._actuator_ids],
                dtype=float,
            )
            for step in range(1, steps + 1):
                fraction = step / steps
                self._set_target(start + fraction * (target - start))
                mujoco.mj_step(self.model, self.data)
        for _ in range(120):
            self._set_target(target)
            mujoco.mj_step(self.model, self.data)

    def reach_task(self, request: Any) -> None:
        self._run_task(request, REACH_TASKS)

    def contact_task(self, request: Any) -> None:
        self._run_task(request, CONTACT_TASKS)

    def fixture_task(self, request: Any) -> None:
        self._run_task(request, FIXTURE_TASKS)

    def rotation_task(self, request: Any) -> None:
        self._run_task(request, ROTATION_TASKS)


def build(*, model: Any, data: Any) -> ReferenceKukaIiwa14Driver:
    return ReferenceKukaIiwa14Driver(model=model, data=data)
