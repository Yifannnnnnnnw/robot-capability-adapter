"""Adapter that normalises method names across agent-written drivers.

Each robot's from-scratch driver is independently generated by the LLM
agent, so method names drift (e.g. `ik` vs `ik_dls` vs `inverse_kinematics`,
`set_arm_actuators` vs `set_joint_controls`). The Gym envs in this module
expect a stable surface; this adapter provides it by forwarding to
whichever name the underlying skel actually has, with sensible fallbacks
implemented directly against `mujoco`.

Usage:
    raw = _load_skeleton_from_workspace(workspace)
    skel = SkelAdapter(raw)
    skel.set_arm_actuators(q)     # works whether raw has set_arm_actuators
                                   # or set_joint_controls or set_joint_positions
    skel.get_object_position("banana")  # works even if raw has no such method
"""
from __future__ import annotations

from typing import Any, Optional

import mujoco
import numpy as np


class SkelAdapter:
    """Thin wrapper exposing a uniform skill API over a loaded skel."""

    def __init__(self, skel: Any) -> None:
        self._skel = skel
        # Cache method choices once
        self._set_arm_method = self._pick_method([
            "set_arm_actuators",
            "set_joint_controls",
            "set_joint_positions",
        ])
        self._ik_method = self._pick_method([
            "ik", "inverse_kinematics", "ik_dls",
        ])
        # MuJoCo handles
        self.model = getattr(skel, "model", None)
        self.data = getattr(skel, "data", None)
        # n_joints / dof fallback
        if hasattr(skel, "dof"):
            self.dof = int(skel.dof)
        elif hasattr(skel, "n_joints"):
            self.dof = int(skel.n_joints)
        else:
            # Last resort: count actuators
            self.dof = int(self.model.nu) if self.model is not None else 0

    # ──────────────────────────────────────────────────────────────────
    def _pick_method(self, candidates: list[str]) -> Optional[str]:
        for name in candidates:
            if hasattr(self._skel, name):
                return name
        return None

    def _q_limits(self) -> tuple[np.ndarray, np.ndarray]:
        if hasattr(self._skel, "_q_lo") and hasattr(self._skel, "_q_hi"):
            return self._skel._q_lo, self._skel._q_hi
        if hasattr(self._skel, "joint_limits"):
            jl = np.asarray(self._skel.joint_limits)
            return jl[:, 0], jl[:, 1]
        # Fallback: read from MuJoCo model
        m = self.model
        lo = m.jnt_range[: self.dof, 0]
        hi = m.jnt_range[: self.dof, 1]
        return lo, hi

    @property
    def _q_lo(self) -> np.ndarray:
        return self._q_limits()[0]

    @property
    def _q_hi(self) -> np.ndarray:
        return self._q_limits()[1]

    # ── Forward attribute access for everything else ─────────────────
    def __getattr__(self, name: str) -> Any:
        # Only called if not found on self / class — i.e. for methods
        # we didn't explicitly override. Forward to underlying skel.
        return getattr(self._skel, name)

    # ── Uniform API ──────────────────────────────────────────────────
    def set_arm_actuators(self, q: np.ndarray) -> None:
        if self._set_arm_method is None:
            raise AttributeError("skel has no actuator setter")
        method = getattr(self._skel, self._set_arm_method)
        method(q)

    def get_joint_velocities(self) -> np.ndarray:
        if hasattr(self._skel, "get_joint_velocities"):
            return self._skel.get_joint_velocities()
        # Fallback: read qvel for the arm joint indices
        if self.data is None or self.model is None:
            return np.zeros(self.dof)
        if hasattr(self._skel, "_arm_joint_ids"):
            ids = self._skel._arm_joint_ids
        elif hasattr(self._skel, "joint_ids"):
            ids = self._skel.joint_ids
        else:
            ids = list(range(self.dof))
        m = self.model
        return np.array(
            [self.data.qvel[m.jnt_dofadr[j]] for j in ids[: self.dof]],
            dtype=np.float64,
        )

    def ik(self, target_xyz: np.ndarray,
            q_init: Optional[np.ndarray] = None,
            *, raise_on_unreachable: Optional[bool] = None) -> np.ndarray:
        """Uniform IK call. Picks the underlying method, passes args.
        If raise_on_unreachable is None we use whatever the underlying does.
        Normalises tuple returns (some drivers return (q, ok))."""
        if self._ik_method is None:
            raise AttributeError("skel has no IK method")
        method = getattr(self._skel, self._ik_method)
        out: Any
        try:
            if raise_on_unreachable is not None:
                out = method(target_xyz, q_init=q_init,
                              raise_on_unreachable=raise_on_unreachable)
            else:
                out = method(target_xyz, q_init=q_init)
        except TypeError:
            try:
                out = method(target_xyz, q_init)
            except TypeError:
                out = method(target_xyz)
        # Normalise tuple return (e.g. Franka's ik_dls returns (q, success))
        if isinstance(out, tuple):
            return np.asarray(out[0], dtype=np.float64)
        return np.asarray(out, dtype=np.float64)

    def get_object_position(self, body_name: str) -> np.ndarray:
        if hasattr(self._skel, "get_object_position"):
            return np.asarray(self._skel.get_object_position(body_name),
                                dtype=np.float64)
        # Fallback: read body xpos directly
        if self.model is None or self.data is None:
            raise AttributeError("skel has no model/data; can't read body pos")
        bid = mujoco.mj_name2id(self.model, mujoco.mjtObj.mjOBJ_BODY, body_name)
        if bid < 0:
            raise ValueError(f"body {body_name!r} not in MJCF")
        return np.asarray(self.data.xpos[bid], dtype=np.float64)

    def settle(self, duration_sec: float = 0.2) -> None:
        if hasattr(self._skel, "settle"):
            self._skel.settle(duration_sec)
            return
        # Fallback: step the sim for N substeps
        if self.model is None or self.data is None:
            return
        dt = self.model.opt.timestep
        n = max(1, int(duration_sec / dt))
        # Some drivers expose step(n_substeps); use that if present
        if hasattr(self._skel, "step"):
            self._skel.step(n)
        else:
            for _ in range(n):
                mujoco.mj_step(self.model, self.data)

    def get_joint_positions(self) -> np.ndarray:
        if hasattr(self._skel, "get_joint_positions"):
            return self._skel.get_joint_positions()
        # Fallback
        m = self.model
        if hasattr(self._skel, "_arm_joint_ids"):
            ids = self._skel._arm_joint_ids
        elif hasattr(self._skel, "joint_ids"):
            ids = self._skel.joint_ids
        else:
            ids = list(range(self.dof))
        return np.array(
            [self.data.qpos[m.jnt_qposadr[j]] for j in ids[: self.dof]],
            dtype=np.float64,
        )

    def get_ee_pose(self):
        return self._skel.get_ee_pose()

    def home(self) -> Any:
        return self._skel.home()

    def step(self, n: int = 1) -> Any:
        return self._skel.step(n)

    def gripper_close(self) -> Any:
        return self._skel.gripper_close()

    def gripper_open(self) -> Any:
        return self._skel.gripper_open()

    def render(self, **kwargs) -> Any:
        return self._skel.render(**kwargs)

    def move_cartesian(self, target_xyz: np.ndarray, duration: float = 2.0) -> Any:
        return self._skel.move_cartesian(target_xyz, duration=duration)
